"""Inspect or verify the pinned HPM SDK integration baseline."""

from __future__ import annotations

import hashlib
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
BASELINE = ROOT / "modules/hpm_sdk/baseline.env"

REQUIRED_KEYS = (
    "HPM_SDK_REVISION",
    "HPM_SDK_VERSION",
    "HPM_SDK_SOC_MODULE_SHA256",
    "HPM_SDK_DRIVER_CMAKE_SHA256",
    "ZEPHYR_REVISION",
)


def _read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        key, separator, value = line.partition("=")
        if not separator or not key or not value:
            raise ValueError(f"invalid baseline entry: {line}")
        values[key] = value
    return values


def _sdk_version(sdk: Path) -> str:
    text = (sdk / "VERSION").read_text(encoding="utf-8")
    values = dict(re.findall(r"^(\w+) = (.*)$", text, re.MULTILINE))
    version = ".".join(
        values[key] for key in ("VERSION_MAJOR", "VERSION_MINOR", "PATCHLEVEL")
    )
    extra = values.get("EXTRAVERSION", "")
    return f"{version}-{extra}" if extra and extra != "0" else version


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _snapshot(sdk: Path, zephyr: Path) -> dict[str, str]:
    return {
        "HPM_SDK_REVISION": _git_revision(sdk),
        "HPM_SDK_VERSION": _sdk_version(sdk),
        "HPM_SDK_SOC_MODULE_SHA256": _sha256(
            sdk / "soc/HPM5300/HPM5361/soc_modules.list"
        ),
        "HPM_SDK_DRIVER_CMAKE_SHA256": _sha256(sdk / "drivers/CMakeLists.txt"),
        "ZEPHYR_REVISION": _git_revision(zephyr),
    }


def _git_revision(path: Path) -> str:
    result = subprocess.run(
        ["git", "-C", str(path), "rev-parse", "HEAD"],
        check=False,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise ValueError(f"not a git checkout: {path}")
    revision = result.stdout.strip()
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError(f"invalid git revision for {path}: {revision}")
    return revision


def _fail(message: str) -> int:
    print(f"error: {message}", file=sys.stderr)
    return 1


def main(argv: list[str]) -> int:
    if len(argv) > 2 or (len(argv) == 2 and argv[1] != "--write"):
        print(f"usage: {argv[0]} [--write]", file=sys.stderr)
        return 2

    sdk_dir = os.environ.get("HPM_SDK_DIR")
    zephyr_dir = os.environ.get("ZEPHYR_BASE")
    if not sdk_dir:
        return _fail("set HPM_SDK_DIR to the pinned HPM SDK checkout")
    if not zephyr_dir:
        return _fail("set ZEPHYR_BASE to the tested Zephyr checkout")

    sdk = Path(sdk_dir).resolve()
    zephyr = Path(zephyr_dir).resolve()
    try:
        actual = _snapshot(sdk, zephyr)
    except (OSError, ValueError) as exc:
        return _fail(str(exc))

    if argv[-1] == "--write":
        lines = [
            "# HPM SDK integration baseline. Generated by scripts/hpm_sdk_baseline.py.",
            "# Update deliberately as part of an SDK upgrade review.",
        ]
        lines.extend(f"{key}={actual[key]}" for key in REQUIRED_KEYS)
        BASELINE.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"wrote {BASELINE.relative_to(ROOT)}")
        return 0

    if not BASELINE.is_file():
        return _fail(f"missing baseline file: {BASELINE.relative_to(ROOT)}")

    try:
        expected = _read_env(BASELINE)
    except (OSError, ValueError) as exc:
        return _fail(str(exc))

    errors = []
    for key in REQUIRED_KEYS:
        if key not in expected:
            errors.append(f"baseline is missing {key}")
        elif expected[key] != actual[key]:
            errors.append(f"{key}: expected {expected[key]}, got {actual[key]}")

    if errors:
        for error in errors:
            print(f"error: {error}", file=sys.stderr)
        print(
            "Run scripts/hpm_sdk_baseline.py --write after reviewing an SDK or Zephyr upgrade.",
            file=sys.stderr,
        )
        return 1

    print("HPM SDK integration baseline: OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
