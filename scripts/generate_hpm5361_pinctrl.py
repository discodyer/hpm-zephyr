PORT_NUMBERS = {"PA": 0, "PB": 32, "PX": 416, "PY": 448}
PORT_IOC = {"PA": "IOC_TYPE_IOC", "PB": "IOC_TYPE_IOC", "PX": "IOC_TYPE_IOC",
            "PY": "IOC_TYPE_PIOC"}
FUNC_RE = re.compile(
    r"^#define (IOC|PIOC)_(P[ABXY])(\d{2})_FUNC_CTL_([A-Z0-9_]+)"
    r"\s+IOC_PAD_FUNC_CTL_ALT_SELECT_SET\((\d+)\)",
    re.MULTILINE,
)


@dataclass(frozen=True, order=True)
class Mux:
    port: str
    pad: int
    ioc: str
    alt: int
    function: str

    @property
    def pad_name(self):
        return f"{self.port}{self.pad:02d}"

    @property
    def label(self):
        return f"{self.pad_name.lower()}_{self.function.lower()}"


def parse_muxes(sdk: Path):
    muxes = {}
    headers = (
        sdk / "soc/HPM5300/HPM5361/hpm_iomux.h",
        sdk / "soc/HPM5300/HPM5361/hpm_pmic_iomux.h",
    )
    for header in headers:
        text = header.read_text(encoding="utf-8")
        for ioc_prefix, port, pad, function, alt in FUNC_RE.findall(text):
            # hpm_pmic_iomux.h contains canonical PIOC definitions plus legacy
            # IOC_PY aliases. Generate only the canonical PIOC nodes there.
            if header.name == "hpm_pmic_iomux.h" and ioc_prefix != "PIOC":
                continue
            ioc = "IOC_TYPE_PIOC" if ioc_prefix == "PIOC" else "IOC_TYPE_IOC"
            key = (port, int(pad), ioc, int(alt), function)
            muxes[key] = Mux(*key)
    return sorted(muxes.values())


def validate_packages(muxes):
    available = {mux.pad_name for mux in muxes}
    all_pads = {f"PA{i:02d}" for i in range(32)} | {f"PB{i:02d}" for i in range(16)}
    all_pads |= {f"PY{i:02d}" for i in range(8)}
    missing = all_pads - available
    if missing:
        raise RuntimeError("SDK is missing IOMUX definitions for: " + ", ".join(sorted(missing)))

    without_gpio = [
        pad
        for pad in all_pads
        if not any(m.pad_name == pad and m.alt == 0 for m in muxes)
    ]
    if without_gpio:
        raise RuntimeError("SDK is missing ALT0 for: " + ", ".join(sorted(without_gpio)))


def format_node(mux):
    pin = f"HPMICRO_PIN(HPMICRO_PORT{mux.port[1]}, {mux.pad})"
    return (
        f"\t/omit-if-no-ref/ {mux.label}: {mux.label} {{\n"
        f"\t\tgroup0 {{\n"
        f"\t\t\tpinmux = <HPMICRO_PINMUX({pin}, {mux.ioc}, 0, {mux.alt})>;\n"
        f"\t\t}};\n"
        f"\t}};\n"
    )


def render(key, metadata, muxes):
    out = [
        "/*",
        " * Copyright (c) 2026 The HPM Zephyr Module Contributors",
        " * SPDX-License-Identifier: Apache-2.0",
        " *",
        " * Auto-generated by scripts/generate_hpm5361_pinctrl.py.",
        f" * Source: HPM5361 {metadata['package']}, {metadata['description']}.",
        " */",
        "",
        "#include <dt-bindings/pinctrl/hpmicro-pinctrl-common.h>",
        "",
        "/ {",
        "\thpm5361_package: hpm5361-package {",
        '\t\tcompatible = "hpmicro,hpm5361-package";',
        f'\t\thpmicro,package = "{metadata["package"].lower()}";',
        f'\t\thpmicro,model = "{metadata["model"]}";',
        f'\t\thpmicro,gpio-count = <{metadata["gpio_count"]}>;',
        f'\t\thpmicro,analog-pin-count = <{metadata["analog_count"]}>;',
        "\t\thpmicro,available-pads =",
    ]

    pads = sorted(metadata["pads"])
    lines = []
    for i in range(0, len(pads), 7):
        chunk = ", ".join(f'"{pad}"' for pad in pads[i:i + 7])
        suffix = ";" if i + 7 >= len(pads) else ","
        lines.append(chunk + suffix)

    if lines:
        out[-1] += " " + lines[0]
        continuation = "\t\t\t\t\t "
        for line in lines[1:]:
            out.append(continuation + line)
    out.extend(["\t};", "};", "", "&pinctrl {"])

    selected = [mux for mux in muxes if mux.pad_name in metadata["pads"]]
    current_port = None
    for mux in selected:
        if mux.ioc != "IOC_TYPE_IOC":
            continue
        if mux.port != current_port:
            out.append(f"\t/* Port {mux.port[1]} */")
            current_port = mux.port
        out.append(format_node(mux))

    if out and out[-1].endswith("\n"):
        out[-1] = out[-1][:-1]
    out.append("};")
    out.extend(["", "&pinctrl {", "\t/* Analog pads */"])
    for pad_name in sorted(metadata["analog_pads"]):
        number = int(pad_name[2:])
        label = f"{pad_name.lower()}_analog"
        out.append(
            f"\t/omit-if-no-ref/ {label}: {label} {{\n"
            f"\t\tgroup0 {{\n"
            f"\t\t\tpinmux = <HPMICRO_PINMUX(HPMICRO_PIN(HPMICRO_PORTB, {number}), "
            f"IOC_TYPE_IOC, 1, 0)>;\n"
            f"\t\t}};\n"
            f"\t}};\n"
        )
    if metadata["analog_pads"]:
        out[-1] = out[-1][:-1]
    out.extend(["};", "", "&pinctrl_pioc {", "\t/* Port Y (PIOC) */"])
    for mux in selected:
        if mux.ioc == "IOC_TYPE_PIOC":
            out.append(format_node(mux))
    # Each formatted node ends with a newline; remove the extra separator
    # immediately before a closing brace.
    if out and out[-1].endswith("\n"):
        out[-1] = out[-1][:-1]
    out.extend(["};"])
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sdk", type=Path, default=DEFAULT_SDK,
                        help="HPM SDK checkout (default: sibling hpm_sdk)")
    parser.add_argument("--check", action="store_true",
                        help="check generated files without writing them")
    args = parser.parse_args()

    muxes = parse_muxes(args.sdk)
    validate_packages(muxes)
    failed = False
    for key, metadata in PACKAGES.items():
        output = OUTPUT_DIR / f"hpm5361-{key}-pinctrl.dtsi"
        generated = render(key, metadata, muxes)
        if args.check:
            if not output.is_file() or output.read_text(encoding="utf-8") != generated:
                print(f"out of date: {output}", file=sys.stderr)
                failed = True
        else:
            output.write_text(generated, encoding="utf-8")
            print(f"generated {output.relative_to(ROOT)}")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
