/** Clear selected interrupt flags for one channel. */
static inline int hpm_sei_clear_events(const struct device *dev, enum hpm_sei_channel channel,
				       uint32_t events)
{
	return DEVICE_API_GET(hpm_sei, dev)->clear_events(dev, channel, events);
}

/**
 * @brief Enable selected SEI interrupts and install a channel callback.
 *
 * Each SEI channel has its own PLIC interrupt. Passing a NULL callback or a
 * zero mask disables all interrupts for that channel.
 *
 * @param dev SEI device.
 * @param channel SEI channel.
 * @param event_mask Combination of HPM_SEI_EVENT_* flags.
 * @param callback Callback invoked from interrupt context.
 * @param user_data Callback context.
 *
 * @retval 0 on success.
 * @retval -EINVAL for an invalid channel or event mask.
 */
static inline int hpm_sei_set_event_callback(const struct device *dev,
					     enum hpm_sei_channel channel, uint32_t event_mask,
					     hpm_sei_event_callback_t callback, void *user_data)
{
	return DEVICE_API_GET(hpm_sei, dev)
		->set_event_callback(dev, channel, event_mask, callback, user_data);
}

